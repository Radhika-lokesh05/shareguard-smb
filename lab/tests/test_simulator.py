def test_cli_stdout_produces_parseable_lines() -> None:
    """CLI with --scenario and output to stdout produces parseable lines."""
    result = subprocess.run(
        [_PYTHON, "-m", "lab.simulate_log", "--scenario", "normal_office", "--duration", "5",
         "--speed", "1000"],
        capture_output=True,
        text=True,
        cwd=str(_WORKSPACE),
        timeout=30,
    )
    assert result.returncode == 0, f"CLI failed: {result.stderr}"
    lines = [ln for ln in result.stdout.splitlines() if ln.strip()]
    assert lines, "CLI produced no output"
    events = parse_lines(lines)
    assert len(events) == len(lines), (
        f"Only {len(events)} of {len(lines)} CLI lines parsed"
    )


def test_cli_out_flag_writes_file(tmp_path: Path) -> None:
    """CLI --out flag writes the log file to disk."""
    out = tmp_path / "cli_test.log"
    result = subprocess.run(
        [_PYTHON, "-m", "lab.simulate_log",
         "--scenario", "attack_fast",
         "--duration", "5",
         "--speed", "1000",
         "--seed", "42",
         "--out", str(out)],
        capture_output=True,
        text=True,
        cwd=str(_WORKSPACE),
        timeout=30,
    )
    assert result.returncode == 0, f"CLI failed: {result.stderr}"
    assert out.exists()
    lines = out.read_text(encoding="utf-8").splitlines()
    assert len(lines) >= 1


def test_cli_unknown_scenario_exits_nonzero() -> None:
    """CLI with an unknown --scenario exits with a non-zero code."""
    result = subprocess.run(
        [_PYTHON, "-m", "lab.simulate_log", "--scenario", "not_a_real_scenario"],
        capture_output=True,
        text=True,
        cwd=str(_WORKSPACE),
        timeout=10,
    )
