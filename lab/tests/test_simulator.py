@pytest.mark.parametrize("scenario", SCENARIO_NAMES)
def test_scenario_produces_lines(scenario: str) -> None:
    """Every scenario yields at least one ScenarioLine."""
    lines = generate_lines(scenario, duration=5.0, speed=100.0, seed=42)
    assert len(lines) >= 1, f"Scenario {scenario!r} produced no lines"


# ---------------------------------------------------------------------------
# Parser round-trip – every generated line must parse cleanly
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("scenario", SCENARIO_NAMES)
def test_scenario_round_trip(scenario: str) -> None:
    """All lines generated by a scenario parse back to valid AuditEvent objects."""
    reset_malformed_count()
    scenario_lines = generate_lines(scenario, duration=10.0, speed=100.0, seed=0)
    raw_lines = [sl.line for sl in scenario_lines]
    events = parse_lines(raw_lines)
    assert len(events) == len(raw_lines), (
        f"Scenario {scenario!r}: {len(raw_lines)} lines generated, "
        f"only {len(events)} parsed. Malformed count: {len(raw_lines) - len(events)}"
    )


