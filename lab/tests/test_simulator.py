def test_generate_event_line_openat_format() -> None:
    """generate_event_line produces a line parseable by parse_line for openat."""
    ts = datetime(2024, 1, 1, 0, 0, 0, tzinfo=UTC)
    line = generate_event_line("alice", "192.168.1.10", "openat", "docs/file.docx", ts=ts)
    evt = parse_line(line)
    assert evt is not None
    assert evt.user == "alice"
    assert evt.ip == "192.168.1.10"
    assert evt.op == "openat"
    assert evt.rel_path == "docs/file.docx"
    assert evt.new_path == ""


def test_generate_event_line_renameat_format() -> None:
    """generate_event_line produces a parseable renameat line."""
    ts = datetime(2024, 1, 1, 0, 0, 0, tzinfo=UTC)
    line = generate_event_line(
        "bob", "10.0.0.55", "renameat", "docs/a.docx", new_path="docs/a.docx.locked", ts=ts
    )
    evt = parse_line(line)
    assert evt is not None
    assert evt.op == "renameat"
    assert evt.rel_path == "docs/a.docx"
    assert evt.new_rel_path == "docs/a.docx.locked"


def test_generate_event_line_unlinkat() -> None:
    """generate_event_line produces a parseable unlinkat line."""
    ts = datetime(2024, 1, 1, 0, 0, 0, tzinfo=UTC)
    line = generate_event_line("carol", "192.168.1.12", "unlinkat", "backup/old.pdf", ts=ts)
