def test_run_simulation_writes_log_and_labels(tmp_path: Path) -> None:
    """run_simulation() creates a log file and a labels CSV with correct columns."""
    log_path = tmp_path / "sim.log"
    labels_path = tmp_path / "sim.labels.csv"

    run_simulation(
        scenario_name="attack_fast",
        out_path=log_path,
        labels_path=labels_path,
        duration=5.0,
        speed=1000.0,
        seed=42,
    )

    # Log file must exist and be non-empty.
    assert log_path.exists()
    log_lines = log_path.read_text(encoding="utf-8").splitlines()
    assert len(log_lines) >= 1

    # All log lines must parse.
    events = parse_lines(log_lines)
    assert len(events) == len(log_lines), (
        f"Only {len(events)} of {len(log_lines)} lines parsed"
    )

    # Labels CSV must exist with correct columns.
    assert labels_path.exists()
    with labels_path.open(encoding="utf-8", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)

    assert rows, "labels.csv is empty"
    expected_columns = {"start", "end", "ip", "user", "scenario", "label"}
    assert expected_columns.issubset(set(rows[0].keys())), (
        f"labels.csv columns: {set(rows[0].keys())}"
    )
    assert all(row["label"] == "1" for row in rows), "attack_fast labels should all be 1"
    assert all(row["scenario"] == "attack_fast" for row in rows)


def test_run_simulation_normal_labels_zero(tmp_path: Path) -> None:
    """run_simulation() with a normal scenario writes label=0 in the CSV."""
    log_path = tmp_path / "normal.log"
